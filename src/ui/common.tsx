export function Kpi({ label, value, delta, deltaGood, title }: { label: string; value: ReactNode; delta?: ReactNode; deltaGood?: boolean | null; title?: string }) {
  return (
    <div className="kpi" title={title}>
      <div className="label">{label}</div>
      <div className="value">{value}</div>
      {delta !== undefined && <div className={`delta ${deltaGood === true ? 'up' : deltaGood === false ? 'down' : ''}`}>{delta}</div>}
    </div>
  );
}

const GOOD = /^(good|low|low risk|regular|comfortable|strong|clean|matched|go|nil|normal|improving|consistent growth|stable|increasing|growing)$/i;
const WARN = /^(moderate|satisfactory|minor delays|acceptable variance|conditional go|stretched|moderate concern|high utilisation|medium|partially matched|growth \(uneven\)|one-off|watchlist|limit not known)/i;
const SERIOUS = /^(high|irregular|material variance|weak|concern|deteriorating|declining|decline|volatile|stressed|large difference|high$)/i;
const CRIT = /^(very high|critical|high concern|investigation required|no-go|high risk|consistent decline|no banking receipt found|very high)/i;
export function statusTone(s: string): 'good' | 'warn' | 'serious' | 'critical' | 'neutral' {
  const t = (s || '').trim();
  if (CRIT.test(t)) return 'critical';
  if (SERIOUS.test(t)) return 'serious';
  if (WARN.test(t)) return 'warn';
  if (GOOD.test(t)) return 'good';
  return 'neutral';
}
const ICON = { good: '●', warn: '▲', serious: '◆', critical: '■', neutral: '○' } as const;
/** Status chip: colour + icon + label (never colour alone). */
export function Chip({ s, tone }: { s: string; tone?: ReturnType<typeof statusTone> | 'info' }) {
  const t = tone || statusTone(s);
  return <span className={`chip ${t}`}>{t !== 'info' && <span aria-hidden>{ICON[t as keyof typeof ICON]}</span>}{s}</span>;
}

export interface Col<T> { key: string; label: string; num?: boolean; render?: (r: T) => ReactNode; sort?: (r: T) => number | string; wrap?: boolean; width?: number }
export function Table<T>({ rows, cols, maxHeight, empty = 'No rows', rowClass, initialSort }: { rows: T[]; cols: Col<T>[]; maxHeight?: number; empty?: string; rowClass?: (r: T) => string; initialSort?: { key: string; dir: 1 | -1 } }) {
  const [sort, setSort] = useState<{ key: string; dir: 1 | -1 } | null>(initialSort || null);
  const exporting = useContext(ExportMode);
  const sorted = useMemo(() => {
    if (!sort) return rows;
    const c = cols.find((x) => x.key === sort.key);
    if (!c?.sort) return rows;
    return [...rows].sort((a, b) => {
      const x = c.sort!(a), y = c.sort!(b);
      return (x > y ? 1 : x < y ? -1 : 0) * sort.dir;
    });
  }, [rows, sort, cols]);
  return (
    <div className="tbl-wrap" style={maxHeight ? { maxHeight } : undefined}>
      <table className="tbl">
        <thead>
          <tr>
            {cols.map((c) => (
              <th key={c.key} className={`${c.num ? 'num' : ''} ${c.sort ? 'sortable' : ''}`} style={c.width ? { width: c.width } : undefined}
                onClick={() => c.sort && setSort((s) => (s?.key === c.key ? { key: c.key, dir: (s.dir * -1) as 1 | -1 } : { key: c.key, dir: -1 }))}>
                {c.label}{sort?.key === c.key ? (sort.dir === 1 ? ' ▲' : ' ▼') : ''}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {sorted.length === 0 && <tr><td colSpan={cols.length} className="muted">{empty}</td></tr>}
          {(exporting ? sorted.slice(0, EXPORT_ROW_LIMIT) : sorted).map((r, i) => (
            <tr key={i} className={rowClass?.(r)}>
              {cols.map((c) => <td key={c.key} className={`${c.num ? 'num' : ''} ${c.wrap ? 'wrap' : ''}`}>{c.render ? c.render(r) : String((r as Record<string, unknown>)[c.key] ?? '')}</td>)}
            </tr>
          ))}
          {exporting && sorted.length > EXPORT_ROW_LIMIT && <tr><td colSpan={cols.length} className="muted small">… {sorted.length - EXPORT_ROW_LIMIT} more rows — full list in the Excel export</td></tr>}
        </tbody>
      </table>
    </div>
  );
}

export function Arrow({ v, better = 'high' }: { v: number | null | undefined; better?: 'high' | 'low' }) {
  if (v === null || v === undefined || !Number.isFinite(v)) return <span className="muted">—</span>;
  const good = better === 'high' ? v >= 0 : v <= 0;
  return <span className={good ? 'up' : 'down'}>{v >= 0 ? '▲' : '▼'} {(Math.abs(v) * 100).toFixed(1)}%</span>;
}

